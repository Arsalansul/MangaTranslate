"""Уточнение вида региона после OCR.

Детектор видит только картинку, и по ней рисованный звук от подписи поверх
арта не отличить: у обоих неровный фон. Поэтому всё, что лежит на рисунке,
он записывает в sfx — осторожно, потому что sfx не стирается вовсе.

OCR приносит недостающее доказательство. Если с региона читаются настоящие
слова, да ещё обычного для этой страницы кегля, это подпись или реплика, а
не мазок: профиль персонажа на серой плашке, хвост фразы, вылезший из
балуна, текст в рваном облаке. Такие регионы возвращаются в перевод.

Модуль намеренно без cv2 и pydantic: правило чисто текстовое, и его можно
прогнать на сохранённых analysis.json, не поднимая контейнер.
"""
import re

# Звук крупнее обычного текста страницы. Порог отделяет "KA-" во всю панель
# от подписи "HAIR COLOR: ORANGE", набранной почти как реплика.
SFX_MAX_RATIO = 1.6

# Ниже этого OCR читает не слова, а шум обводки. Такому региону веры нет:
# лучше оставить мазок, чем стереть рисунок и вписать в него кашу.
TEXTY_CONF = 0.5

# Буква любой письменности, не цифра и не подчёркивание. Латиница здесь
# частный случай: по [A-Za-z] не словом оказывались и хангыль с ханьцзы,
# и французское «été».
_WORD = re.compile(r"[^\W\d_]{2,}", re.UNICODE)

# Знаки препинания, законные внутри реплики. ASCII-набора мало: в корейской
# и японской вёрстке точка, запятая и кавычки — свои символы, и без них
# осмысленная фраза не добирает порог чистоты и объявляется мусором.
_PUNCT = set(".,!?'\"-:"            # ASCII, как было
             "…—–‘’“”«»¡¿"          # европейская типографика
             "。、！？，：；"           # CJK-точка, запятая, полноширинные знаки
             "「」『』（）〈〉《》【】"  # CJK-скобки и кавычки
             "〜～・ー")               # тильда, разделитель, знак долготы

# Длина, начиная с которой слово считается осмысленным. У бескассовых
# письменностей знак несёт слог или морфему целиком, и подпись из двух
# иероглифов — обычное дело; латинское слово в две буквы чаще обломок.
_MIN_LEN_CASED = 3
_MIN_LEN_CASELESS = 2


def _cased(word: str) -> bool:
    """Есть ли в слове буквы с понятием регистра.

    У ханьцзы, хангыля и каны верхнего и нижнего регистра нет вовсе, поэтому
    проверки, написанные под латиницу, к ним неприменимы — их надо не
    ослаблять для всех, а не применять к бескассовым.
    """
    return word.lower() != word.upper()


def wordish(text: str) -> bool:
    """Похоже ли прочитанное на слова, а не на обломки обводки.

    Ошибиться в эту сторону дороже, чем в другую: пропущенный звук так и
    останется мазком, а ложное слово будет стёрто с рисунка и заменено
    переводом мусора. Поэтому проверок три и все строгие.
    """
    text = (text or "").strip()
    if not text:
        return False

    # Слово набрано ровно: ВЕРХНИМ, нижним или С Заглавной. Пляшущий
    # регистр внутри слова ("GoFPY") — почерк OCR по обводке звука.
    # Бескассовое слово эту проверку пройти не может физически, а не
    # потому, что плохо прочитано, — с него она и не спрашивается.
    words = [w for w in _WORD.findall(text)
             if not _cased(w) or w.isupper() or w.islower() or w.istitle()]
    if not any(len(w) >= (_MIN_LEN_CASED if _cased(w) else _MIN_LEN_CASELESS)
               for w in words):
        return False

    # Между словами не должно быть свалки из обломков глифов.
    clean = sum(1 for c in text if c.isalnum() or c.isspace() or c in _PUNCT)
    return clean >= 0.7 * len(text)


def revise_kinds(regions) -> int:
    """Возвращает в перевод подписи, принятые за звук. Считает исправленные."""
    body = sorted(int(r.font_px or 0) for r in regions
                  if r.kind in ("bubble", "caption") and r.font_px)
    if not body:
        return 0
    limit = body[len(body) // 2] * SFX_MAX_RATIO

    fixed = 0
    for r in regions:
        if (r.kind == "sfx"
                and float(r.conf or 0) >= TEXTY_CONF
                and int(r.font_px or 0) <= limit
                and wordish(r.text)):
            r.kind = "caption"
            fixed += 1
    return fixed
